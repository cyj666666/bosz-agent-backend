--   报表类型（源数据仅以下四种）：000 通用财务 | 020 新会计准则 | 019 事业单位财务报表 | 030 担保公司财务报表
--   指标            000                    020                     019                  030
--   营业收入         PS 501                 PS 501                  RDSI 501             PS 2001
--   营业收入同比     FIS 984                FIS 984                 -                    FIS A0501
--   净利润           PS 517                 PS/PSN 517 或 6506(哪个有值取哪个)  RDSI 517  PS 333
