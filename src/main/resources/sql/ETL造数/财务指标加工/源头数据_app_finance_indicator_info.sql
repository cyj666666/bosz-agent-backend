-- 1. 幂等：先删除本次加工范围内的全部目标行（含不再保留的非最新/非年报期），再由下方 INSERT 仅回写保留的三档，重跑不叠加
DELETE FROM app_finance_indicator_info
WHERE (customerId = 'CUST-001' OR 'CUST-001' IS NULL)
  AND (reportNo   = 'RPT-202609-001'   OR 'RPT-202609-001'   IS NULL);

-- 2. 加工：主表去重 + 从表(分科目透视->按类型选列) + 指标计算 -> app_finance_indicator_info
INSERT INTO app_finance_indicator_info (
    reportNo, customerId, customerName, guarantorId, guarantorName, subjectType, finReportNo, accountMonth, reportScope, reportPeriod,
    auditFlag, currency, monetaryUnit, reportStatusName, reportStatus, reportTypeNo, reportTypeName ,
    revenue, revenueYoY, netProfit, netProfitYoY, paidInCapital, totalEquity,
    accountsReceivable, arChangeFromYearStart, arChangeFromYearStartRate,
    otherReceivable, orChangeFromYearStart, orChangeFromYearStartRate, arOrTotalAssetRatio,
    shortLoan, shortLoanChangeFromYearStart, shortLoanChangeFromYearStartRate,
    longLoan, longLoanChangeFromYearStart, longLoanChangeFromYearStartRate,
    longLoanDueWithin1Y, salesLoanRatio,
    notesPayable, notepayablechangefromyearstart, notepayablechangefromyearstartRate,
    otherPayable, otherPayableChangeFromYearStart, otherPayableChangeFromYearStartRate,
    slTotalLoanYoy, arYoy, arTurnoverDays, inventoryTurnoverDays, inventoryYoy,
    accountsPayable, inventory, debtRatio, salesProfitRatio, netProfitRatio,
    inputTime
)
SELECT
    r.reportNo AS reportNo,
    r.customerId AS customerId,
    r.customerName AS customerName,
    -- guarantorId/guarantorName 语义=「该行主体」：担保人=担保主体；借款人=借款人自身(customerId/customerName)，
    -- 使两列恒有值（与 app_guarantor_info 借款人行口径一致）。注意仅输出列兜底，r/t 内部分区与同比 JOIN 仍用源 guarantorId
    CASE WHEN r.subjectType = '担保人' THEN r.guarantorId ELSE r.customerId END AS guarantorId,
    CASE WHEN r.subjectType = '担保人' THEN r.guarantorName ELSE r.customerName END AS guarantorName,
    r.subjectType AS subjectType,
    r.finReportNo AS finReportNo,
    r.accountMonth AS accountMonth,
    CASE r.reportScope WHEN '1' THEN '合并' WHEN '2' THEN '本部' WHEN '3' THEN '汇总' ELSE r.reportScope END AS reportScope,
    CASE r.reportPeriod WHEN '01' THEN '月报' WHEN '02' THEN '季报' WHEN '03' THEN '半年报' WHEN '04' THEN '年报' WHEN '05' THEN '其他' ELSE r.reportPeriod END AS reportPeriod,
    r.auditFlag AS auditFlag,
    r.currency AS currency,
    '万' AS monetaryUnit,
    r.reportStatusName AS reportStatusName,
    r.reportStatus AS reportStatus,
    r.reportTypeNo AS reportTypeNo,
    r.reportTypeName AS reportTypeName,
    p.rev_v2 * r.unitFactor AS revenue,
    p.revYoY_v2 * 100 AS revenueYoY,
    p.np_v2 * r.unitFactor AS netProfit,
    p.npYoY_v2 * 100 AS netProfitYoY,
    p.pic_v2 * r.unitFactor AS paidInCapital,
    p.te_v2 * r.unitFactor AS totalEquity,
    p.ar_v2 * r.unitFactor AS accountsReceivable,
    (p.ar_v2 - p.ar_v1) * r.unitFactor AS arChangeFromYearStart,
    CASE WHEN p.ar_v1 IS NOT NULL AND p.ar_v1 <> 0 THEN (p.ar_v2 - p.ar_v1) / p.ar_v1 * 100 END AS arChangeFromYearStartRate,
    p.or_v2 * r.unitFactor AS otherReceivable,
    (p.or_v2 - p.or_v1) * r.unitFactor AS orChangeFromYearStart,
    CASE WHEN p.or_v1 IS NOT NULL AND p.or_v1 <> 0 THEN (p.or_v2 - p.or_v1) / p.or_v1 * 100 END AS orChangeFromYearStartRate,
    CASE WHEN p.ta_v2 IS NOT NULL AND p.ta_v2 <> 0 THEN (p.ar_v2 + p.or_v2) / p.ta_v2 * 100 END AS arOrTotalAssetRatio,
    p.sl_v2 * r.unitFactor AS shortLoan,
    (p.sl_v2 - p.sl_v1) * r.unitFactor AS shortLoanChangeFromYearStart,
    CASE WHEN p.slRate_v1 IS NOT NULL AND p.slRate_v1 <> 0 THEN (p.slRate_v2 - p.slRate_v1) / p.slRate_v1 * 100 END AS shortLoanChangeFromYearStartRate,
    p.ll_v2 * r.unitFactor AS longLoan,
    (p.ll_v2 - p.ll_v1) * r.unitFactor AS longLoanChangeFromYearStart,
    CASE WHEN p.ll_v1 IS NOT NULL AND p.ll_v1 <> 0 THEN (p.ll_v2 - p.ll_v1) / p.ll_v1 * 100 END AS longLoanChangeFromYearStartRate,
    p.ll1y_v2 * r.unitFactor AS longLoanDueWithin1Y,
    CASE WHEN r.reportPeriod = '04' AND p.rev_v2 IS NOT NULL AND p.rev_v2 <> 0
          THEN (p.slRate_v2 + p.ll1y_v2) / p.rev_v2 * 100 END AS salesLoanRatio,
    p.npay_v2 * r.unitFactor AS notesPayable,
    (p.npay_v2 - p.npay_v1) * r.unitFactor AS notepayablechangefromyearstart,
    CASE WHEN p.npay_v1 IS NOT NULL AND p.npay_v1 <> 0 THEN (p.npay_v2 - p.npay_v1) / p.npay_v1 * 100 END AS notepayablechangefromyearstartRate,
    p.opay_v2 * r.unitFactor AS otherPayable,
    (p.opay_v2 - p.opay_v1) * r.unitFactor AS otherPayableChangeFromYearStart,
    CASE WHEN p.opay_v1 IS NOT NULL AND p.opay_v1 <> 0 THEN (p.opay_v2 - p.opay_v1) / p.opay_v1 * 100 END AS otherPayableChangeFromYearStartRate,
    CASE WHEN (p.slRate_v2 + p.ll_v2) IS NOT NULL AND (t.ly_slRate_v2 + t.ly_ll_v2) IS NOT NULL AND (t.ly_slRate_v2 + t.ly_ll_v2) <> 0
         THEN (p.slRate_v2 + p.ll_v2 - (t.ly_slRate_v2 + t.ly_ll_v2)) / (t.ly_slRate_v2 + t.ly_ll_v2) * 100 END AS slTotalLoanYoy,
    CASE WHEN p.ar_v2 IS NOT NULL AND t.ly_ar_v2 IS NOT NULL AND t.ly_ar_v2 <> 0
         THEN (p.ar_v2 - t.ly_ar_v2) / t.ly_ar_v2 * 100 END AS arYoy,
    CASE WHEN p.arTo_v2 IS NOT NULL AND p.arTo_v2 <> 0 THEN CAST(365 / p.arTo_v2 AS INTEGER) END AS arTurnoverDays,
    CASE WHEN p.invTo_v2 IS NOT NULL AND p.invTo_v2 <> 0 THEN CAST(365 / p.invTo_v2 AS INTEGER) END AS inventoryTurnoverDays,
    CASE WHEN p.inv_v2 IS NOT NULL AND t.ly_inv_v2 IS NOT NULL AND t.ly_inv_v2 <> 0
         THEN (p.inv_v2 - t.ly_inv_v2) / t.ly_inv_v2 * 100 END AS inventoryYoy,
    p.ap_v2 * r.unitFactor AS accountsPayable,
    p.inv_v2 * r.unitFactor AS inventory,
    p.dr_v2 * 100 AS debtRatio,
    p.spr_v2 * 100 AS salesProfitRatio,
    p.npr_v2 * 100 AS netProfitRatio,
    CURRENT_TIMESTAMP AS inputTime
FROM (
    -- 主表：按入参过滤 + 同 finReportNo 仅保留最新一期 + app 层仅保留「最新一期 / 去年同期(同口径同月上一年) / 全部年报」
    --   最新一期   = 该 (客户,报告,口径,主体) 下 accountMonth 最大的一期
    --   去年同期   = 与「最新一期」同口径(reportScope)、同报表周期(reportPeriod)、同月(accountMonth 后 2 位)、上一年（前 4 位 -1）的一期
    --                （如最新=202603 半年报，则保留 202503 半年报；与「上一期」不同：上一期是同报表周期内次新一期，去年同期固定为上一年同月同周期，与同比 t 表口径一致）
    --   全部年报   = reportPeriod = '04'（年报）的全部历史期
    SELECT reportNo, customerId, customerName, guarantorId, guarantorName, subjectType, corpOrgId, finReportNo, accountMonth,
           reportScope, reportPeriod, monetaryUnit, currency,
           reportStatus, reportStatusName, auditFlag, reportTypeNo, reportTypeName, inputtime,
           CASE WHEN monetaryUnit IN ('1', '元') THEN 0.0001
                WHEN monetaryUnit IN ('1000', '千') THEN 0.1
                WHEN monetaryUnit IN ('10000', '万', '万元') THEN 1
                WHEN monetaryUnit IN ('100000', '十万') THEN 10
                WHEN monetaryUnit IN ('1000000', '百万') THEN 100
                WHEN monetaryUnit IN ('10000000', '千万') THEN 1000
                WHEN monetaryUnit IN ('100000000', '亿') THEN 10000
                ELSE 1 END AS unitFactor
    FROM (
        -- d3：rpLatest = 「最新一期」(accountMonth=amMax) 所在期的报表周期（用于判定「去年同期」的报表周期）
        SELECT d2.*,
               MAX(CASE WHEN d2.accountMonth = d2.amMax THEN d2.reportPeriod END) OVER (
                   PARTITION BY d2.customerId, d2.reportNo, d2.reportScope, COALESCE(d2.guarantorId, '')) AS rpLatest
        FROM (
            -- d2：amMax = 该 (客户,报告,口径,主体) 下最新会计月（= 最新一期；用于推导去年同期会计月）
            SELECT d1.*,
                   MAX(d1.accountMonth) OVER (
                       PARTITION BY d1.customerId, d1.reportNo, d1.reportScope, COALESCE(d1.guarantorId, '')) AS amMax
            FROM (
                -- d1：入参过滤 + 同 finReportNo 仅保留最新一期
                SELECT r.*,
                       ROW_NUMBER() OVER (PARTITION BY r.finReportNo
                                          ORDER BY r.inputtime DESC, r.id DESC) AS rn
                FROM xd_financial_report r
                WHERE r.finReportNo IS NOT NULL
                  AND (r.customerId = 'CUST-001' OR 'CUST-001' IS NULL)
                  AND (r.reportNo   = 'RPT-202609-001'   OR 'RPT-202609-001'   IS NULL)
            ) d1
            WHERE d1.rn = 1
        ) d2
    ) d3
    WHERE d3.reportPeriod = '04'              -- ③ 全部年报
       OR d3.accountMonth = d3.amMax          -- ① 最新一期（accountMonth 最大）
       OR (d3.reportPeriod = d3.rpLatest
           AND d3.accountMonth = CONCAT(CAST(SUBSTR(d3.amMax, 1, 4) AS INTEGER) - 1, SUBSTR(d3.amMax, 5)))  -- ② 去年同期（同口径、同报表周期、同月、上一年，与同比 t 表口径一致）
) r
LEFT JOIN (
    -- p：按报表类型(rtype)从"分科目列"选出该类型对应的指标值（canonical 列）
    SELECT finReportNo,
        CASE rtype WHEN '000' THEN ps_501_v2    WHEN '020' THEN ps_501_v2    WHEN '019' THEN rdsi_501_v2 WHEN '030' THEN ps_2001_v2 END AS rev_v2,
        CASE rtype WHEN '000' THEN fis_984_v2   WHEN '020' THEN fis_984_v2   WHEN '030' THEN fis_a0501_v2 END AS revYoY_v2,
        CASE rtype WHEN '000' THEN ps_517_v2    WHEN '020' THEN COALESCE(ps_517_v2, psn_517_v2, psn_6506_v2)
                         WHEN '019' THEN rdsi_517_v2 WHEN '030' THEN ps_333_v2 END AS np_v2,
        CASE rtype WHEN '000' THEN fis_921_v2   WHEN '020' THEN fis_921_v2   WHEN '030' THEN fis_a0502_v2 END AS npYoY_v2,
        CASE rtype WHEN '000' THEN bs_301_v2    WHEN '020' THEN bs_301_v2    WHEN '030' THEN bs_301_v2 END AS pic_v2,
        CASE rtype WHEN '000' THEN bs_808_v2    WHEN '020' THEN bs_808_v2    WHEN '019' THEN bs_808_v2 WHEN '030' THEN bs_808_v2 END AS te_v2,
        CASE rtype WHEN '000' THEN bs_104_v2    WHEN '020' THEN bs_106_v2    WHEN '019' THEN bs_19f_v2  WHEN '030' THEN bs_104_v2 END AS ar_v2,
        CASE rtype WHEN '000' THEN bs_104_v1    WHEN '020' THEN bs_106_v1    WHEN '019' THEN bs_19f_v1  WHEN '030' THEN bs_104_v1 END AS ar_v1,
        CASE rtype WHEN '000' THEN bs_108_v2    WHEN '020' THEN bs_108_v2    WHEN '019' THEN bs_19e_v2 WHEN '030' THEN 0 END AS or_v2,
        CASE rtype WHEN '000' THEN bs_108_v1    WHEN '020' THEN bs_108_v1    WHEN '019' THEN bs_19e_v1  END AS or_v1,
        CASE rtype WHEN '000' THEN bs_804_v2    WHEN '020' THEN bs_804_v2    WHEN '019' THEN bs_19d_v2  WHEN '030' THEN bs_804_v2 END AS ta_v2,
        CASE rtype WHEN '000' THEN bs_102_v2    WHEN '020' THEN bs_201_v2    WHEN '019' THEN bs_275_v2  WHEN '030' THEN bs_201_v2 END AS sl_v2,
        CASE rtype WHEN '000' THEN bs_102_v1    WHEN '020' THEN bs_201_v1    WHEN '019' THEN bs_275_v1  WHEN '030' THEN bs_201_v1 END AS sl_v1,
        -- 短期借款增幅专用（000 按 Excel 规则取 201，其余与 sl 相同）
        CASE rtype WHEN '000' THEN bs_201_v2    WHEN '020' THEN bs_201_v2    WHEN '019' THEN bs_275_v2  WHEN '030' THEN bs_201_v2 END AS slRate_v2,
        CASE rtype WHEN '000' THEN bs_201_v1    WHEN '020' THEN bs_201_v1    WHEN '019' THEN bs_275_v1  WHEN '030' THEN bs_201_v1 END AS slRate_v1,
        CASE rtype WHEN '000' THEN bs_213_v2    WHEN '020' THEN bs_213_v2    WHEN '019' THEN bs_275a_v2 WHEN '030' THEN bs_213_v2 END AS ll_v2,
        CASE rtype WHEN '000' THEN bs_213_v1    WHEN '020' THEN bs_213_v1    WHEN '019' THEN bs_275a_v1 WHEN '030' THEN bs_213_v1 END AS ll_v1,
        CASE rtype WHEN '000' THEN bs_211_v2    WHEN '020' THEN bs_643_v2     WHEN '030' THEN bs_211_v2  END AS ll1y_v2,
        CASE rtype WHEN '000' THEN bs_202_v2    WHEN '020' THEN bs_202_v2    WHEN '019' THEN bs_202_v2  END AS npay_v2,
        CASE rtype WHEN '000' THEN bs_202_v1    WHEN '020' THEN bs_202_v1    WHEN '019' THEN bs_202_v1  END AS npay_v1,
        CASE rtype WHEN '000' THEN bs_209_v2    WHEN '020' THEN bs_209_v2    WHEN '019' THEN bs_209_v2  END AS opay_v2,
        CASE rtype WHEN '000' THEN bs_209_v1    WHEN '020' THEN bs_209_v1    WHEN '019' THEN bs_209_v1  END AS opay_v1,
        CASE rtype WHEN '000' THEN bs_203_v2    WHEN '020' THEN bs_203_v2    WHEN '019' THEN bs_203_v2  WHEN '030' THEN bs_200_v2 END AS ap_v2,
        CASE rtype WHEN '000' THEN bs_110_v2    WHEN '020' THEN bs_110_v2    END AS inv_v2,
        CASE rtype WHEN '000' THEN fis_908_v2    WHEN '020' THEN fis_908_v2    END AS invTo_v2,
        CASE rtype WHEN '000' THEN fis_907_v2    WHEN '020' THEN fis_907_v2    END AS arTo_v2,
        CASE rtype WHEN '000' THEN fis_911_v2   WHEN '020' THEN fis_911_v2   WHEN '019' THEN fis_911_v2 WHEN '030' THEN fis_911_v2 END AS dr_v2,
        CASE rtype WHEN '000' THEN fis_901_v2   WHEN '020' THEN fis_901_v2   END AS spr_v2,
        CASE rtype WHEN '000' THEN fis_903_v2   END AS npr_v2
    FROM (
        -- piv：每个科目 (sheetNo + subjectNo) 透视为独立列，各自持有自己的 value（v1 期初 / v2 期末）
        SELECT finReportNo, rtype,
            -- 营业收入
            MAX(CASE WHEN sheetNo = 'PS'   AND subjectNo = '501'  THEN v2n END) AS ps_501_v2,
            MAX(CASE WHEN sheetNo = 'RDSI' AND subjectNo = '501'  THEN v2n END) AS rdsi_501_v2,
            MAX(CASE WHEN sheetNo = 'PS'   AND subjectNo = '2001' THEN v2n END) AS ps_2001_v2,
            -- 营业收入同比
            MAX(CASE WHEN sheetNo = 'FIS'  AND subjectNo = '984'   THEN v2n END) AS fis_984_v2,
            MAX(CASE WHEN sheetNo = 'FIS'  AND subjectNo = 'A0501' THEN v2n END) AS fis_a0501_v2,
            -- 净利润
            MAX(CASE WHEN sheetNo = 'PS'   AND subjectNo = '517'  THEN v2n END) AS ps_517_v2,
            MAX(CASE WHEN sheetNo = 'PSN'  AND subjectNo = '517'  THEN v2n END) AS psn_517_v2,
            MAX(CASE WHEN sheetNo = 'PSN'  AND subjectNo = '6506' THEN v2n END) AS psn_6506_v2,
            MAX(CASE WHEN sheetNo = 'RDSI' AND subjectNo = '517'  THEN v2n END) AS rdsi_517_v2,
            MAX(CASE WHEN sheetNo = 'PS'   AND subjectNo = '333'  THEN v2n END) AS ps_333_v2,
            -- 净利润同比
            MAX(CASE WHEN sheetNo = 'FIS'  AND subjectNo = '921'   THEN v2n END) AS fis_921_v2,
            MAX(CASE WHEN sheetNo = 'FIS'  AND subjectNo = 'A0502' THEN v2n END) AS fis_a0502_v2,
            -- 实收资本
            MAX(CASE WHEN sheetNo = 'BS'   AND subjectNo = '301'  THEN v2n END) AS bs_301_v2,
            -- 所有者权益合计
            MAX(CASE WHEN sheetNo = 'BS'   AND subjectNo = '808'  THEN v2n END) AS bs_808_v2,
            -- 应收账款（v2 期末 / v1 期初）
            MAX(CASE WHEN sheetNo = 'BS'   AND subjectNo = '104'  THEN v2n END) AS bs_104_v2,
            MAX(CASE WHEN sheetNo = 'BS'   AND subjectNo = '104'  THEN v1n END) AS bs_104_v1,
            MAX(CASE WHEN sheetNo = 'BS'   AND subjectNo = '106'  THEN v2n END) AS bs_106_v2,
            MAX(CASE WHEN sheetNo = 'BS'   AND subjectNo = '106'  THEN v1n END) AS bs_106_v1,
            MAX(CASE WHEN sheetNo = 'BS'   AND subjectNo = '19f'  THEN v2n END) AS bs_19f_v2,
            MAX(CASE WHEN sheetNo = 'BS'   AND subjectNo = '19f'  THEN v1n END) AS bs_19f_v1,
            -- 其他应收款
            MAX(CASE WHEN sheetNo = 'BS'   AND subjectNo = '108'  THEN v2n END) AS bs_108_v2,
            MAX(CASE WHEN sheetNo = 'BS'   AND subjectNo = '108'  THEN v1n END) AS bs_108_v1,
            MAX(CASE WHEN sheetNo = 'BS'   AND subjectNo = '19e'  THEN v2n END) AS bs_19e_v2,
            MAX(CASE WHEN sheetNo = 'BS'   AND subjectNo = '19e'  THEN v1n END) AS bs_19e_v1,
            -- 资产总计
            MAX(CASE WHEN sheetNo = 'BS'   AND subjectNo = '804'  THEN v2n END) AS bs_804_v2,
            MAX(CASE WHEN sheetNo = 'BS'   AND subjectNo = '19d'  THEN v2n END) AS bs_19d_v2,
            -- 短期借款
            MAX(CASE WHEN sheetNo = 'BS'   AND subjectNo = '102'  THEN v2n END) AS bs_102_v2,
            MAX(CASE WHEN sheetNo = 'BS'   AND subjectNo = '102'  THEN v1n END) AS bs_102_v1,
            MAX(CASE WHEN sheetNo = 'BS'   AND subjectNo = '201'  THEN v2n END) AS bs_201_v2,
            MAX(CASE WHEN sheetNo = 'BS'   AND subjectNo = '201'  THEN v1n END) AS bs_201_v1,
