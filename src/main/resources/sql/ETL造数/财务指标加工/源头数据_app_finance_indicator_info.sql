            -- 一年内到期的长期借款
            MAX(CASE WHEN sheetNo = 'BS'   AND subjectNo = '211'  THEN v2n END) AS bs_211_v2,
            MAX(CASE WHEN sheetNo = 'BS'   AND subjectNo = '643'   THEN v2n END) AS bs_643_v2,
            -- 应付票据
            MAX(CASE WHEN sheetNo = 'BS'   AND subjectNo = '202'  THEN v2n END) AS bs_202_v2,
