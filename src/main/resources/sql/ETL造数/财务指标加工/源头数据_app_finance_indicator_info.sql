            -- 应付账款
            MAX(CASE WHEN sheetNo = 'BS'   AND subjectNo = '203'  THEN v2n END) AS bs_203_v2,
            MAX(CASE WHEN sheetNo = 'BS'   AND subjectNo = '200'  THEN v2n END) AS bs_200_v2,
            -- 存货
            MAX(CASE WHEN sheetNo = 'BS'   AND subjectNo = '110'  THEN v2n END) AS bs_110_v2,
            -- 存货周转率
            MAX(CASE WHEN sheetNo = 'FIS'   AND subjectNo = '908'  THEN v2n END) AS fis_908_v2,
            -- 应收账款周转率
            MAX(CASE WHEN sheetNo = 'FIS'   AND subjectNo = '907'  THEN v2n END) AS fis_907_v2,
            -- 资产负债率
            MAX(CASE WHEN sheetNo = 'FIS'  AND subjectNo = '911'  THEN v2n END) AS fis_911_v2,
            -- 销售利润率
            MAX(CASE WHEN sheetNo = 'FIS'  AND subjectNo = '901'  THEN v2n END) AS fis_901_v2,
            -- 净利率
            MAX(CASE WHEN sheetNo = 'FIS'  AND subjectNo = '903'  THEN v2n END) AS fis_903_v2
        FROM (
            -- x：从表去重，每个 (finReportNo, sheetNo, subjectNo) 仅保留最新一条，并做数字校验
            SELECT s.finReportNo, s.sheetNo, s.subjectNo, r2.rtype,
                    CAST(NULLIF(TRIM(s.value1), '') AS DECIMAL) AS v1n,
                    CAST(NULLIF(TRIM(s.value2), '') AS DECIMAL) AS v2n,
                   ROW_NUMBER() OVER (PARTITION BY s.finReportNo, s.sheetNo, s.subjectNo
                                      ORDER BY s.inputtime DESC, s.id DESC) AS rn
            FROM xd_financial_subject s
            JOIN (
                -- 每个 finReportNo 的报表类型（取最新一期，与主表口径一致）
                SELECT finReportNo, reportTypeNo AS rtype
                FROM (
                    SELECT r3.finReportNo, r3.reportTypeNo,
                           ROW_NUMBER() OVER (PARTITION BY r3.finReportNo
                                              ORDER BY r3.inputtime DESC, r3.id DESC) AS rn2
                    FROM xd_financial_report r3
                    WHERE r3.finReportNo IS NOT NULL
                      AND (r3.customerId = 'CUST-001' OR 'CUST-001' IS NULL)
                      AND (r3.reportNo   = 'RPT-202609-001'   OR 'RPT-202609-001'   IS NULL)
                ) t2
                WHERE t2.rn2 = 1
            ) r2 ON r2.finReportNo = s.finReportNo
            WHERE s.finReportNo IS NOT NULL
        ) x
        WHERE x.rn = 1
        GROUP BY finReportNo, rtype
    ) piv
) p ON p.finReportNo = r.finReportNo
LEFT JOIN (
    -- t：去年同期派生表（自 xd_financial_yoy.sql 内联）：每个 (客户, 口径, 周期, 会计月, 主体) 取最新一期
    --    去年同期是另一份报表(reportNo 不同)，故只按 'CUST-001' 过滤，不能按 'RPT-202609-001' 过滤；
    --    同比按主体匹配（COALESCE(guarantorId,'') 对齐），借款人与担保人各自同比、互不串数
    SELECT customerId, reportScope, reportPeriod, accountMonth, guarantorId,
           ly_slRate_v2, ly_ll_v2, ly_ar_v2, ly_inv_v2
    FROM (
        SELECT
            rr.customerId, rr.reportScope, rr.reportPeriod, rr.accountMonth, rr.guarantorId,
            pt.slRate_v2 AS ly_slRate_v2,
            pt.ll_v2     AS ly_ll_v2,
            pt.ar_v2     AS ly_ar_v2,
            pt.inv_v2    AS ly_inv_v2,
            ROW_NUMBER() OVER (PARTITION BY rr.customerId, rr.reportScope, rr.reportPeriod, rr.accountMonth, COALESCE(rr.guarantorId, '')
                               ORDER BY rr.inputtime DESC, rr.id DESC) AS rn3
        FROM (
            -- 报表按 finReportNo 去重取最新，带 customerId/reportScope/accountMonth/reportPeriod/主体（不带 reportNo 过滤）
            SELECT finReportNo, customerId, reportScope, accountMonth, reportPeriod, guarantorId, inputtime, id
            FROM (
                SELECT r4.*,
                       ROW_NUMBER() OVER (PARTITION BY r4.finReportNo
                                          ORDER BY r4.inputtime DESC, r4.id DESC) AS rn
                FROM xd_financial_report r4
                WHERE r4.finReportNo IS NOT NULL
                  AND (r4.customerId = 'CUST-001' OR 'CUST-001' IS NULL)
                  AND REGEXP_LIKE(r4.accountMonth, '^[0-9]{6}$')
            ) tt
            WHERE tt.rn = 1
        ) rr
        LEFT JOIN (
            -- 与 p 相同的 piv，仅取同比所需四科目；value2 口径与 p 一致
            SELECT finReportNo,
                CASE rtype WHEN '000' THEN bs_201_v2   WHEN '020' THEN bs_201_v2   WHEN '019' THEN bs_275_v2   WHEN '030' THEN bs_201_v2   END AS slRate_v2,
                CASE rtype WHEN '000' THEN bs_213_v2   WHEN '020' THEN bs_213_v2   WHEN '019' THEN bs_275a_v2  WHEN '030' THEN bs_213_v2   END AS ll_v2,
                CASE rtype WHEN '000' THEN bs_104_v2   WHEN '020' THEN bs_106_v2   WHEN '019' THEN bs_19f_v2   WHEN '030' THEN bs_104_v2   END AS ar_v2,
                CASE rtype WHEN '000' THEN bs_110_v2   WHEN '020' THEN bs_110_v2   END AS inv_v2
            FROM (
                SELECT finReportNo, rtype,
                    MAX(CASE WHEN sheetNo = 'BS' AND subjectNo = '201'  THEN v2n END) AS bs_201_v2,
                    MAX(CASE WHEN sheetNo = 'BS' AND subjectNo = '275'  THEN v2n END) AS bs_275_v2,
                    MAX(CASE WHEN sheetNo = 'BS' AND subjectNo = '213'  THEN v2n END) AS bs_213_v2,
                    MAX(CASE WHEN sheetNo = 'BS' AND subjectNo = '275a' THEN v2n END) AS bs_275a_v2,
                    MAX(CASE WHEN sheetNo = 'BS' AND subjectNo = '104'  THEN v2n END) AS bs_104_v2,
                    MAX(CASE WHEN sheetNo = 'BS' AND subjectNo = '106'  THEN v2n END) AS bs_106_v2,
                    MAX(CASE WHEN sheetNo = 'BS' AND subjectNo = '19f'  THEN v2n END) AS bs_19f_v2,
                    MAX(CASE WHEN sheetNo = 'BS' AND subjectNo = '110'  THEN v2n END) AS bs_110_v2
                FROM (
                    -- x：从表去重，每个 (finReportNo, sheetNo, subjectNo) 仅保留最新一条（value2 口径与 p 侧一致）
                    SELECT s.finReportNo, s.sheetNo, s.subjectNo, r2.rtype,
                           CAST(NULLIF(TRIM(s.value2), '') AS DECIMAL) AS v2n,
                           ROW_NUMBER() OVER (PARTITION BY s.finReportNo, s.sheetNo, s.subjectNo
                                              ORDER BY s.inputtime DESC, s.id DESC) AS rn
                    FROM xd_financial_subject s
                    JOIN (
                        SELECT finReportNo, reportTypeNo AS rtype
                        FROM (
                            SELECT r5.finReportNo, r5.reportTypeNo,
                                   ROW_NUMBER() OVER (PARTITION BY r5.finReportNo
                                                      ORDER BY r5.inputtime DESC, r5.id DESC) AS rn2
                            FROM xd_financial_report r5
                            WHERE r5.finReportNo IS NOT NULL
                              AND (r5.customerId = 'CUST-001' OR 'CUST-001' IS NULL)
                        ) t2
                        WHERE t2.rn2 = 1
                    ) r2 ON r2.finReportNo = s.finReportNo
                    WHERE s.finReportNo IS NOT NULL
                ) x
                WHERE x.rn = 1
                GROUP BY finReportNo, rtype
            ) piv
        ) pt ON pt.finReportNo = rr.finReportNo
    ) q
    WHERE q.rn3 = 1
) t
    ON t.customerId   = r.customerId
    AND t.reportScope  = r.reportScope
    AND t.reportPeriod = r.reportPeriod
    AND t.accountMonth = CONCAT(CAST(SUBSTR(r.accountMonth, 1, 4) AS INTEGER) - 1, SUBSTR(r.accountMonth, 5))
    AND COALESCE(t.guarantorId, '') = COALESCE(r.guarantorId, '');
