（七）其他可能对本行授信资产产生不利影响符合黄色预警定义的事项。
橙色预警等级：指系统推送或在授信业务各阶段发现预警信号，经排查发现借款人正常生产经营或工作产生一定影响，借款人还款能力出现问题，预计会产生风险，但可通过其他还款来源进行补救。需高度重视，密切关注借款人债务状况，尽快评估分析，根据评估结果动态调整应急方案。包括不限于如下情形：
