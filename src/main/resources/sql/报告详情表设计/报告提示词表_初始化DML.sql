（四）主要经营活动变化：员工人数、用电量、上缴税款等无合理理由大幅减少，拖欠社保；核心业务发生较大变动，市场竞争力下降或市场份额出现较大幅度的下滑；业务伙伴关系恶化，重要上下游伙伴流失；法定代表人/实际控制人死亡，但不会对我行信贷资产安全造成严重影响；受到新闻媒体负面报道，影响可控的等；
（五）内外部信用评级下滑：外部机构下调借款人的信用评级；A级以下客户年度内部评级相比上年下降3级或以上；个人信用行为评分连续两期下降等；
