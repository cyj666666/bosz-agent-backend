# 预警管理办法（定级依据，严格按此判定）
黄色预警等级：指系统推送或在授信业务各阶段发现预警信号，经排查对借款人正常生产经营或工作影响较小，且借款人仍有强烈还款意愿及还款能力，暂未形成实质性风险。需进一步调查了解预警信号成因，跟踪借款人风险形势，推动风险化解进程。包括不限于如下情形：
